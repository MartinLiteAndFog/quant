UTC = dt.timezone.utc
BOX = 0.1
SPLIT_SEC = 1788739200  # 2026-09-07 00:00:00Z, observed in TV archive snapshot
DEFAULT_WARMUP_SEC = 1785000000  # 2026-07-25


def parse_ms(s: str) -> int:
    t = dt.datetime.fromisoformat(s.replace('Z', '+00:00'))
    if t.utcoffset() is None:
        raise ValueError('All reference timestamps must be timezone-aware UTC ISO-8601')
    return round(t.timestamp() * 1000)


def iso_ms(ms: int) -> str:
    return dt.datetime.fromtimestamp(ms / 1000, UTC).isoformat(timespec='milliseconds').replace('+00:00','Z')


@dataclass(frozen=True)
class RenkoBrick:
    ts_ms: int
    open: float
    high: float
    low: float
    close: float

    def __post_init__(self) -> None:
        if not isinstance(self.ts_ms, int) or not all(math.isfinite(v) and v > 0 for v in (self.open,self.high,self.low,self.close)):
            raise ValueError('Renko OHLC must be finite positive and timestamp integer milliseconds')
        if self.high + 1e-8 < max(self.open,self.close) or self.low - 1e-8 > min(self.open,self.close):
            raise ValueError('Invalid Renko OHLC extremes')


def read_binance_gz(path: Path, warmup_sec: int = DEFAULT_WARMUP_SEC) -> list[tuple[int, float]]:
    """Read 1m Binance OHLC from pipe-delimited gzip, no interpolation or lookahead.

    Returns only complete minute samples in [warmup, end], preserving start-label.
    A missing source minute prevents a higher-timeframe candle from completing.
    """
    rows = []
    last = -1
    with gzip.open(path, 'rt', encoding='utf-8') as handle:
        for line in handle:
            if not line.strip():
                continue
            parts = line.rstrip().split('|')
            if len(parts) < 5:
                raise ValueError('Malformed Binance 1m gzip row')
            ts = int(parts[0])
            if ts < warmup_sec:
                continue
            close = float(parts[4])
            if ts <= last or ts % 60 != 0 or not math.isfinite(close) or close <= 0:
                raise ValueError('Unordered/invalid Binance minute timestamp or close')
            rows.append((ts, close))
            last = ts
    if not rows:
        raise ValueError('No valid source closes')
    return rows


def complete_source_candles(minutes: Iterable[tuple[int, float]], period_seconds: int) -> dict[int, float]:
    """UTC start-labeled candle closing prices; refuse incomplete/gapped buckets."""
    if period_seconds < 60 or period_seconds % 60:
        raise ValueError('period_seconds must be a positive multiple of 60')
    buckets: dict[int, tuple[float,int,int,int]] = {}
    for ts, close in minutes:
        start = ts // period_seconds * period_seconds
        previous = buckets.get(start)
        if previous is None:
            buckets[start] = (close,1,ts,ts)
        else:
            _,count,first,last = previous
            if ts != last + 60:
                # A gap makes candle ineligible; counted candles cannot be backfilled.
                buckets[start] = (close,-999,first,ts)
            else:
                buckets[start] = (close,count+1,first,ts)
    n = period_seconds // 60
    return {start: close for start,(close,count,first,last) in buckets.items()
            if count == n and first == start and last == start + period_seconds - 60}


def reconstruct_renko_with_wicks(
    ordered_close_sources: Iterable[tuple[int,float]], box: float = BOX,
) -> list[RenkoBrick]:
    """Traditional close-source TV history: 1-box continuation, 2-box reversal.

    For first brick in a source candle, a counter-direction wick records the
    maximum/minimum **source closes observed since previous emitted brick**,
    not underlying intraminute high/low. Multiple emitted bricks get 1ms stamps.
    """
    sources = list(ordered_close_sources)
    if not sources or not math.isfinite(box) or box <= 0:
        raise ValueError('Need a nonempty source and positive Renko box size')
    ts0,initial = sources[0]
    close = round(math.floor((initial + 1e-10) / box) * box,12)
    trend = 0
    high_so_far = low_so_far = initial
    result: list[RenkoBrick] = []
    last_source = -1
    tol = box * 1e-9
    for ts,price in sources:
        if ts <= last_source or not math.isfinite(price) or price <= 0 or ts % 300 != 0:
            raise ValueError('Sources must be ordered, positive 5m-or-H1 close labels')
        last_source = ts
        low_so_far = min(low_so_far, price)
        high_so_far = max(high_so_far, price)
        emitted = 0
        def emit(direction: int, op: float, end: float) -> None:
            nonlocal close, trend, emitted
            if emitted == 0:
                wick_low = low_so_far if direction == +1 and low_so_far < op-box-tol else min(op,end)
                wick_high = high_so_far if direction == -1 and high_so_far > op+box+tol else max(op,end)
            else:
                wick_low,wick_high = min(op,end),max(op,end)
            result.append(RenkoBrick(ts*1000 + emitted,round(op,4),
                                     round(max(op,end,wick_high),4),
                                     round(min(op,end,wick_low),4),round(end,4)))
            close = round(end,12)
            trend = direction
            emitted += 1
        if trend >= 0:
            if price >= close + box-tol:
                while price >= close + box-tol:
                    emit(+1,close,close+box)
            elif trend == +1 and price <= close - 2*box+tol:
                emit(-1,close-box,close-2*box)
                while price <= close-box+tol:
                    emit(-1,close,close-box)
            elif trend == 0 and price <= close-box+tol:
                while price <= close-box+tol:
                    emit(-1,close,close-box)
        else:
            if price <= close-box+tol:
                while price <= close-box+tol:
                    emit(-1,close,close-box)
            elif price >= close+2*box-tol:
                emit(+1,close+box,close+2*box)
                while price >= close+box-tol:
                    emit(+1,close,close+box)
        if emitted:
            low_so_far = high_so_far = close
    return result


def independent_5m_renko(minute_closes: Iterable[tuple[int,float]], split_sec: int = SPLIT_SEC):
    minutes=list(minute_closes)
    h1=complete_source_candles(minutes,3600)
    m5=complete_source_candles(minutes,300)
    sources=sorted([(k,v) for k,v in h1.items() if k<split_sec] +
                   [(k,v) for k,v in m5.items() if k>=split_sec])
    if not sources or len(sources)<100:
        raise ValueError('Need historical warmup and enough valid source data')
    last_complete_m5 = max((k for k in m5 if k>=split_sec),default=None)
    if last_complete_m5 is None:
        raise ValueError('No complete post-switch 5m candles')
    return reconstruct_renko_with_wicks(sources), (last_complete_m5+300)*1000


@dataclass(frozen=True)
class StopSettings:
    stop_loss_fraction: float
    trailing_fraction: float
    activation_fraction: float = 0.0

    def __post_init__(self):
        if not all(math.isfinite(x) for x in (self.stop_loss_fraction,self.trailing_fraction,self.activation_fraction)):
            raise ValueError('Stop settings must be finite')
        if not(0 < self.stop_loss_fraction < .20 and 0 < self.trailing_fraction < .20
               and 0 <= self.activation_fraction < .20):
            raise ValueError('Stop settings out of bounds')


@dataclass(frozen=True)
class PredictedExit:
    ts_ms: int
    stop_level: float
    trigger: str  # "fixed_stop" or "armed_trailing"
    side: str


class ExitMachine:
    """One position, non-lookahead brick-order stop state, no knowledge of exit tape.

    Following entry, fixed protective stop is active. A zero-activation TTP
    arms only after a subsequent favorable chart high/low. At every new Renko
    brick, check the *previously established* stop before updating favorable
    extreme from that brick (avoid same-bar stop-level lookahead). At first touch
    return a stop event; no trades/capital are affected.
    """
    def __init__(self, entry_ms: int, entry_price: float, side: str, settings: StopSettings):
        if side not in ('long','short') or not math.isfinite(entry_price) or entry_price <= 0:
            raise ValueError('Entry price and side must be valid')
        self.entry_ms = entry_ms
        self.entry_price = entry_price
        self.side = side
        self.settings = settings
        self.best = entry_price
        self.armed = False
        self.closed = False
        self.last_seen = -1

    def stop_level(self) -> tuple[float,str]:
        s = self.settings
        if self.side == 'long':
            fixed = self.entry_price*(1-s.stop_loss_fraction)
            trail = self.best*(1-s.trailing_fraction)
            active = self.armed and trail > fixed
            return (trail if active else fixed), ('armed_trailing' if active else 'fixed_stop')
        fixed = self.entry_price*(1+s.stop_loss_fraction)
        trail = self.best*(1+s.trailing_fraction)
        active = self.armed and trail < fixed
        return (trail if active else fixed), ('armed_trailing' if active else 'fixed_stop')

    def advance(self, brick: RenkoBrick) -> PredictedExit | None:
        if self.closed:
            raise RuntimeError('Position already closed')
        if brick.ts_ms <= self.last_seen:
            raise ValueError('Renko sequence out of order')
        self.last_seen = brick.ts_ms
        if brick.ts_ms <= self.entry_ms:
            return None
        stop,kind = self.stop_level()
        touched = brick.low <= stop+1e-9 if self.side == 'long' else brick.high >= stop-1e-9
        if touched:
            self.closed = True
            return PredictedExit(brick.ts_ms,round(stop,7),kind,self.side)
        favorable = brick.high if self.side == 'long' else brick.low
        self.best = max(self.best,favorable) if self.side == 'long' else min(self.best,favorable)
        moved = (self.best/self.entry_price-1) if self.side == 'long' else (1-self.best/self.entry_price)
        if moved > self.settings.activation_fraction+1e-10:
            self.armed=True
        return None


def predict_exit(bricks: list[RenkoBrick], ts_index: list[int], entry_time: int,
                 entry_price: float, side: str, settings: StopSettings) -> PredictedExit | None:
    machine=ExitMachine(entry_time, entry_price, side, settings)
    for brick in bricks[bisect.bisect_right(ts_index, entry_time):]:
        hit=machine.advance(brick)
        if hit is not None:
            return hit
    return None


def source_config(seed: dict) -> StopSettings:
    attrs=seed['originalSettings']['safePropertyRows']
    props={str(k).strip():str(v).strip() for k,v in attrs}
    if props.get('💰 Take Profit Type') != 'Trailing TP %' or props.get('📛 Stop Loss Type') != 'SL %':
        raise ValueError('Only the audited Tradingade SL% + trailing-TP% export is supported')
    if float(props.get('🚀TTP  %','NaN')) != 0:
        raise ValueError('Only the observed zero-activation TTP% is supported')
    attrs=seed['candidateGenes']
    return StopSettings(float(attrs['stopLossBps'])/10000,
                        float(attrs['trailingDeviationBps'])/10000)


def checked_reference_flips(seed: dict) -> dict[str,int]:
    closed=seed['trades']['closed']
    entries={(t['entryUtc'],t['side'],round(float(t['entryPrice']),2)) for t in closed}
    if seed['trades'].get('open'):
        entries.update((t['entryUtc'],t['side'],round(float(t['entryPrice']),2))
                       for t in seed['trades']['open'])
    flips=[t for t in closed if t['exitSignal'] in ('short','long')]
    matched=sum((t['exitUtc'],t['exitSignal'],round(float(t['exitPrice']),2)) in entries for t in flips)
    return {'reference_flip_exits':len(flips),'continuing_opposite_entries':matched,
            'unpaired_flip_exits':len(flips)-matched}


def analyze_manifest(manifest: dict, bricks: list[RenkoBrick], fully_covered_until_ms: int) -> tuple[dict,list[dict]]:
    if manifest.get('schemaVersion')!=2 or manifest.get('sourceTimeZone')!='Europe/Berlin' or not manifest.get('secretsExcluded'):
        raise ValueError('Expected sanitized v2 Europe/Berlin source-time-normalized manifest')
    for i in range(1,len(bricks)):
        if bricks[i].ts_ms<=bricks[i-1].ts_ms:raise ValueError('Nonmonotone Renko timestamps')
    times=[b.ts_ms for b in bricks]
    rows=[];flip_stats={}; all_counts=Counter(); comparable=0
    for seed in manifest.get('seeds',[]):
        flip_stats[seed['id']]=checked_reference_flips(seed)
        if seed['instrument']['symbol']!='BINANCE:SOLUSDT':continue
        settings=source_config(seed)
        for trade in seed['trades']['closed']:
            row={'seedId':seed['id'],'tradeNumber':int(trade['number']),'side':trade['side'],
                 'referenceExitLabel':trade['exitSignal'],'referenceEntryUtc':trade['entryUtc'],
                 'referenceExitUtc':trade['exitUtc'],'referenceEntryPx':trade['entryPrice'],
                 'referenceExitPx':trade['exitPrice'],
                 'modelOrigin':'reference_entry_only__independent_Binance_1m_Renko_exits',
                 'status':None,'predictedExitUtc':None,'predictedExitPx':None,'predictedBoundary':None,
                 'timeDeltaMs':None,'priceDeltaQuote':None,
                 'exactMillisecond':False,'same5mSourceBucket':False,'priceWithin2c':False,'bothExactMsAnd2c':False}
            if trade['exitSignal'] not in ('SL','TP'):
                row['status']='flip_reference_not_predicted'
            else:
                entry_ms=parse_ms(trade['entryUtc']);exit_ms=parse_ms(trade['exitUtc'])
                if entry_ms<times[0] or exit_ms>fully_covered_until_ms or entry_ms>fully_covered_until_ms:
                    row['status']='outside_complete_Binance_source_window'
                else:
                    event=predict_exit(bricks,times,entry_ms,float(trade['entryPrice']),trade['side'],settings)
                    if event is None or event.ts_ms>fully_covered_until_ms:
                        row['status']='no_exit_found_in_complete_source_window'
                    else:
                        comparable+=1
                        dt_ms=event.ts_ms-exit_ms
                        err=float(event.stop_level)-float(trade['exitPrice'])
                        is_ts=dt_ms==0
                        px_ok=abs(err)<.02+1e-10
                        row.update(status='predicted',predictedExitUtc=iso_ms(event.ts_ms),
                                   predictedExitPx=event.stop_level,predictedBoundary=event.trigger,
                                   timeDeltaMs=dt_ms,priceDeltaQuote=round(err,7),
                                   exactMillisecond=is_ts,same5mSourceBucket=(event.ts_ms//300000==exit_ms//300000),
                                   priceWithin2c=px_ok,bothExactMsAnd2c=(is_ts and px_ok))
            rows.append(row)
            all_counts[row['status']]+=1
    evaluated=[r for r in rows if r['status']=='predicted']
    unq={(
        r['referenceEntryUtc'],r['side'],r['referenceEntryPx'],
        r['referenceExitUtc'],r['referenceExitPx'],r['referenceExitLabel'],
        # same stop/dev within all Binance SOL seed variants
      ):r for r in evaluated}
    def stats(pairs):
        return {'n':len(pairs),
                'exact_ms':sum(bool(r['exactMillisecond']) for r in pairs),
                'same_5m_bucket':sum(bool(r['same5mSourceBucket']) for r in pairs),
                'price_within_2c':sum(bool(r['priceWithin2c']) for r in pairs),
                'exact_ms_and_price_2c':sum(bool(r['bothExactMsAnd2c']) for r in pairs)}
    summary={
       'claim':'research_only_reference_entry_anchored__not_independent_strategy_backtest',
       'source':'Binance SOLUSDT 1m closes -> complete H1 before split / 5m after -> Traditional Renko OHLC and wicks',
       'time_split_utc':iso_ms(SPLIT_SEC*1000),
       'source_coverage_complete_until_utc':iso_ms(fully_covered_until_ms),
       'reference_tradingview_exit_tape_is_used_only_for_posthoc_comparison':True,
       'no_live_orders_no_capital_vigor_bookings':True,
       'all_reference_rows':len(rows), 'status_counts':dict(all_counts),
       'all':stats(evaluated),
       'unique_reference_trades':stats(list(unq.values())),
       'by_exit_reference_label':{label:stats([r for r in evaluated if r['referenceExitLabel']==label]) for label in ('TP','SL')},
       'by_seed':{seed['id']:stats([r for r in evaluated if r['seedId']==seed['id']]) for seed in manifest.get('seeds',[]) if seed['instrument']['symbol']=='BINANCE:SOLUSDT'},
       'reference_flip_continuity_only':flip_stats,
       'limitations':[
          'TV entry timestamp, price, side are fixed reference anchors; no independent Elliott Wave/RSI entry production.',
          'No intrabar tick ordering from 1m; reconstructed Renko is synthetic chart geometry and not a realizable fill.',
          '37+ nonaligned exits are not silently adjusted/calibrated; one anomalous RSI-off variant dominates.',
          'Overlapping Strategy Builder snapshots duplicate trades; unique_reference_trades is a deduplicated view.',
          'This does not validate original Tradingade stop-order activation, flip entry generation or margin accounting.',
       ],
    }
    return summary,rows


def export_audit(out_dir: Path,summary: dict, rows: list[dict]) -> None:
    out_dir.mkdir(parents=True,exist_ok=True)
    (out_dir/'tradingade_exit_reference_anchored_summary.json').write_text(json.dumps(summary,indent=2,ensure_ascii=False)+'\n')
    with (out_dir/'tradingade_exit_reference_anchored_details.csv').open('w',newline='',encoding='utf-8') as f:
        fields=list(rows[0]) if rows else []
        w=csv.DictWriter(f,fieldnames=fields)
        w.writeheader();w.writerows(rows)


def main() -> None:
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--binance-1m-gz',type=Path,required=True)
    ap.add_argument('--manifest-v2',type=Path,required=True)
    ap.add_argument('--out-dir',type=Path,required=True)
    ap.add_argument('--warmup-utc',default='2026-07-25T00:00:00Z')
    args=ap.parse_args()
    rows=read_binance_gz(args.binance_1m_gz,parse_ms(args.warmup_utc)//1000)
    bricks,last_full=independent_5m_renko(rows)
    manifest=json.loads(args.manifest_v2.read_text())
    summary,details=analyze_manifest(manifest,bricks,last_full)
    summary['source_sha256']={str(args.binance_1m_gz.name):hashlib.file_digest(open(args.binance_1m_gz,'rb'),'sha256').hexdigest(),
                               str(args.manifest_v2.name):hashlib.file_digest(open(args.manifest_v2,'rb'),'sha256').hexdigest()}
    summary['source_1m_loaded_minutes']=len(rows)
    summary['reconstructed_renko_bricks_including_warmup']=len(bricks)
    export_audit(args.out_dir,summary,details)
    print(json.dumps(summary,indent=2,ensure_ascii=False))

if __name__=='__main__':
    main()